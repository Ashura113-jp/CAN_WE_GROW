function startGame() {
  window.clearInterval(gameTimer);
  window.clearTimeout(feedbackTimer);
  score = 0;
  timeLeft = gameLength;
  active = true;
  updateGameStats();
  bubbles.forEach((bubble) => {
    bubble.disabled = false;
    bubble.classList.remove("popped");
  });
  gameOverlay.hidden = true;
  bubbleField.classList.add("is-active");
  gameState.textContent = translate("bubble.active");
  gameButton.querySelector(".button-label").textContent = translate("bubble.restart");
  gameMessage.textContent = translate("bubble.playing");
  gameTimer = window.setInterval(() => {
    timeLeft -= 1;
    updateGameStats();
    if (timeLeft <= 0) finishGame();
  }, 1000);
}

