function applyLanguage(language) {
  currentLanguage = language === "ja" ? "ja" : "en";
  document.documentElement.lang = currentLanguage;
  document.title = translate("page.title");
  document.querySelector('meta[name="description"]').content = translate("meta.description");
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    element.innerHTML = translate(element.dataset.i18n);
  });
  document.querySelectorAll("[data-i18n-aria]").forEach((element) => {
    element.setAttribute("aria-label", translate(element.dataset.i18nAria));
  });
  document.querySelectorAll("[data-language]").forEach((button) => {
    const selected = button.dataset.language === currentLanguage;
    button.classList.toggle("is-selected", selected);
    button.setAttribute("aria-pressed", String(selected));
  });
  document.querySelectorAll("[data-game-title]").forEach((element) => {
    element.textContent = translate(`game.${element.dataset.gameTitle}.title`);
  });
  document.querySelectorAll("[data-game-description]").forEach((element) => {
    element.textContent = translate(`game.${element.dataset.gameDescription}.description`);
  });
  document.querySelectorAll("[data-game-launch]").forEach((element) => {
    element.textContent = translate(`game.${element.dataset.gameLaunch}.launch`);
  });
  document.querySelectorAll("[data-game-moods]").forEach((element) => {
    element.textContent = translate(`game.${element.dataset.gameMoods}.moods`);
  });
  document.querySelectorAll("[data-bubble-number]").forEach((element) => {
    element.setAttribute("aria-label", translate("bubble.bubble", { n: element.dataset.bubbleNumber }));
  });
  promptElement.textContent = promptsShown
    ? promptLists[currentLanguage][previousPrompt]
    : translate("joy.initial");
  promptCount.textContent = promptsShown
    ? translate("joy.count", { n: promptsShown })
    : translate("joy.fresh");
  gameState.textContent = translate(active ? "bubble.active" : timeLeft === 0 ? "bubble.done" : "bubble.paused");
  const gameButtonLabel = gameButton.querySelector(".button-label");
  if (gameButtonLabel) gameButtonLabel.textContent = translate(active ? "bubble.restart" : timeLeft === 0 ? "bubble.again" : "bubble.start");
  gameOverlay.querySelector("span:last-child").textContent = translate(timeLeft === 0 ? "bubble.overlay.done" : "bubble.overlay.ready");
  gameMessage.textContent = active
    ? translate("bubble.playing")
    : timeLeft === 0
      ? translate(score === 1 ? "bubble.result.one" : "bubble.result.other", { n: score })
      : translate("bubble.ready");
  updateGameStats();
}



